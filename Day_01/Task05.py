# Task 5: Convert a temperature from Celsius to Fahrenheit and display it with two decimal places.

celsius = float(input("Enter temperature in Celsius: ").strip())
fahrenheit = (celsius * 9/5) + 32
print(f" \n The temperature in Fahrenheit is : {fahrenheit:.2f} \n")
